"""Дозапись в текстовые области логов — пачкой, а не построчно.

Измерено: `appendHtml` стоит около 390 мкс на строку независимо от её длины —
каждый вызов разбирает разметку, пересобирает документ и трогает полосу
прокрутки. Пока строк единицы, это незаметно; на такте монитора их приходит
сотнями, а при открытии окна логов — тысячами, и цена умножается. Настоящий
лог в 11 879 строк заливался 4,9 с построчно и 0,38 с одной вставкой: в
тринадцать раз. Столько же стоит каждое переключение отсева в поиске, потому
что оно перерисовывает весь буфер.

Каждая строка оборачивается в свой <div>: иначе вставка слилась бы в один
блок, а по блокам считается `maximumBlockCount` и ходит поиск. Пустая строка
блока не создаёт вовсе (проверено: пять кусков дали три блока), поэтому в неё
кладём нулевой пробел — на экране его не видно, а строка остаётся строкой.
"""
from __future__ import annotations

import re

_EMPTY = "&#8203;"      # нулевой пробел: блок есть, на экране пусто
_TAGS = re.compile(r"<[^>]*>")


def _blank(piece: str) -> bool:
    """Кусок, от которого на экране ничего не останется.

    Проверять саму строку недостаточно: пустая строка лога приходит сюда уже
    завёрнутой в <span style=...>, то есть непустой, а блока всё равно не
    создаёт. На настоящем логе так пропала двадцать одна строка из 8620 —
    пустые и состоящие из пробелов. Отступы внутри таких строк теряются, но
    их и так съедает разметка.
    """
    return not _TAGS.sub("", piece).strip()


def append_html(view, pieces) -> None:
    """Дописывает готовые HTML-куски: один кусок — одна строка в окне."""
    if not isinstance(pieces, list):
        pieces = list(pieces)
    if not pieces:
        return
    if len(pieces) == 1:
        # одна строка — как раньше, без лишней обёртки
        view.appendHtml(pieces[0] if not _blank(pieces[0]) else _EMPTY)
        return
    view.appendHtml("".join(f"<div>{_EMPTY if _blank(p) else p}</div>"
                            for p in pieces))
