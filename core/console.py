"""Скрытая консоль для собранной версии.

pboProject — GUI-программа (подсистема 2), а работу делает консольными
помощниками: MakePbo, PboDeps, ExtractPbo. Консольное приложение, запущенное
там, где консоли нет ни у кого, заводит себе свою — с видимым окном. При
запаковке мода их выскакивает по одному на каждый шаг.

Из исходников этого не видно: приложение запущено из терминала, консоль есть,
и вся цепочка её наследует. В собранном виде (console=False в спеке) консоли
нет, отсюда и окна.

CREATE_NO_WINDOW у запуска pboProject не помогает: флаг документирован для
консольных приложений, а pboProject GUI-шный — для него он не действует.
Перенаправить вывод помощников тоже нельзя, pboProject от этого ломается
(см. core/packer).

Поэтому заводим консоль себе и прячем окно. Помощники наследуют её и остаются
невидимыми, вывод при этом никуда не перенаправляется — консоль настоящая.

Проверено на модели «GUI-родитель запускает консольную программу»: без этого
у ребёнка своя консоль с видимым окном, с этим — наша, скрытая.
"""
from __future__ import annotations

import ctypes
import sys

_SW_HIDE = 0


def hide() -> bool:
    """Заводит скрытую консоль, если её нет. True — завели.

    Ничего не делает там, где консоль уже есть: из терминала мы работаем в ней,
    и прятать чужое окно нельзя.
    """
    if sys.platform != "win32":
        return False
    try:
        k = ctypes.windll.kernel32
        u = ctypes.windll.user32
        k.GetConsoleWindow.restype = ctypes.c_void_p
        if k.GetConsoleWindow():
            return False                      # консоль уже есть — не трогаем
        if not k.AllocConsole():
            return False
        hwnd = k.GetConsoleWindow()
        if hwnd:
            u.ShowWindow(ctypes.c_void_p(hwnd), _SW_HIDE)
        return True
    except (AttributeError, OSError):
        # без консоли приложение работает, просто при запаковке будут окна
        return False
